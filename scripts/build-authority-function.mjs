/**
 * Bundles the trusted authority host (server/authority/host.ts) and the kernel
 * it needs into ONE ES module for the `helm-authority` edge function:
 * supabase/functions/helm-authority/kernel.mjs.
 *
 * The kernel is plain TypeScript with no runtime dependencies (the Postgres
 * adapters import only the Supabase client's TYPES), so the bundle is
 * self-contained; the function supplies the clients.
 *
 *   npm run build:authority-function
 */

import { rolldown } from 'rolldown';
import { statSync } from 'node:fs';

const out = 'supabase/functions/helm-authority/kernel.mjs';
const bundle = await rolldown({
  input: 'server/authority/host.ts',
  platform: 'neutral',
  external: [/^@supabase\//],
  resolve: { conditionNames: ['import', 'default'] },
});
await bundle.write({ file: out, format: 'esm', minify: true, banner: '// Generated by scripts/build-authority-function.mjs from server/authority/host.ts — do not edit.' });
await bundle.close();
console.log(`build:authority-function — ${out} (${(statSync(out).size / 1024).toFixed(1)} KiB)`);
